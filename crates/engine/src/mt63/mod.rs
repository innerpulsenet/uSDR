/// The rate MT63 is defined at.
const RATE: f32 = 8000.0;
/// Integration of the synchronizer and decoder, in symbols: fldigi's
/// "long" setting, which its author recommends for weak signals.
const INTEG: usize = 32;
/// How far behind the synchronizer the data is read, in symbols. fldigi
/// reads at [`INTEG`] behind; then a short-interleave opening (32 symbols)
/// is still going past while the synchronizer settles and the first
/// characters are lost. Half as much again costs a second or so.
const DATA_DELAY: usize = INTEG * 3 / 2;

/// Symbols of sustained agreement before anything prints: synchronizer
/// locked, the decoder's smoothed Walsh peak at or over [`S_OPEN`], one
/// carrier offset throughout.
const OPEN_RUN: u32 = 20;
/// Symbols kept while shut, so that what was decoded before the gate opened
/// (the start of a transmission, weakest at the lock) is not lost.
const HELD: usize = 128;
/// The decoder's smoothed Walsh peak over the RMS of the transform's rest.
/// Noise alone stayed at or under 3.2 for 180 s of every mode, steady
/// carriers with FT8-like 8-FSK at or under 4.2 (`gate_margins` in the
/// tests).
const S_OPEN: f32 = 5.0;
/// Once open, it stays open while the smoothed peak holds this.
const S_HOLD: f32 = 4.0;
/// Symbols under [`S_HOLD`] that close it.
const CLOSE_RUN: u32 = 8;
/// A character prints if its own Walsh peak reaches this: a peak that
/// stands out of the other 63 by more than noise commonly reaches.
const CHAR_MIN: f32 = 4.5;
/// Non-blank characters a burst must reach before it prints.
const MIN_BURST: usize = 4;
/// SNR readings averaged, in symbols of good copy.
const SNR_AVERAGE: u32 = 8;
/// Pending text is let go after this long without a character.
const FLUSH_S: f32 = 4.0;

/// One MT63 setting.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Mt63Config {
    /// 500, 1000 or 2000.
    pub bandwidth_hz: u32,
    /// Long interleave (64 symbols) or short (32).
    pub long: bool,
    /// The middle of the band in the audio.
    pub center_hz: f32,
    /// fldigi's 8-bit option: code 127 escapes a code above 127.
    pub eight_bit: bool,
}

impl Default for Mt63Config {
    fn default() -> Self {
        Self {
            bandwidth_hz: 1000,
            long: true,
            center_hz: 1500.0,
            eight_bit: false,
        }
    }
}

impl Mt63Config {
    pub fn new(bandwidth_hz: u32, long: bool, center_hz: f32) -> Self {
        Self {
            bandwidth_hz: match bandwidth_hz {
                500 | 1000 | 2000 => bandwidth_hz,
                b if b < 750 => 500,
                b if b < 1500 => 1000,
                _ => 2000,
            },
            long,
            center_hz,
            eight_bit: false,
        }
    }

    /// The label fldigi uses, MT63-1000L and so on.
    pub fn label(&self) -> String {
        format!(
            "MT63-{}{}",
            self.bandwidth_hz,
            if self.long { "L" } else { "S" }
        )
    }
}

#[derive(Clone, Debug, PartialEq)]
pub enum Mt63Event {
    /// Decoded text, a line at a time (or what there is after a pause).
    Text {
        text: String,
        mode: String,
        center_hz: f32,
        snr_db: f32,
    },
}

impl Mt63Event {
    pub fn kind(&self) -> &'static str {
        match self {
            Mt63Event::Text { .. } => "text",
        }
    }

    pub fn summary(&self) -> String {
        match self {
            Mt63Event::Text { text, mode, .. } => format!("{mode}: {text}"),
        }
    }

    pub fn fields(&self) -> Vec<(&'static str, String)> {
        match self {
            Mt63Event::Text {
                text,
                mode,
                center_hz,
                snr_db,
            } => vec![
                ("text", text.clone()),
                ("mode", mode.clone()),
                ("centerHz", format!("{center_hz:.1}")),
                ("snrDb", format!("{snr_db:.1}")),
            ],
        }
    }
}

#[derive(Clone, Debug, PartialEq)]
pub struct Mt63Status {
    /// A burst is being printed.
    pub locked: bool,
    /// Where the signal's band center is, as last found (the configured
    /// center when nothing has been found).
    pub center_hz: f32,
    /// Signal to noise in 2500 Hz while printing; None until something has
    /// been printed.
    pub snr_db: Option<f32>,
    /// The setting the signal was found with, as "MT63-1000L".
    pub mode: String,
    /// Characters printed since the decoder was made.
    pub chars: u64,
}

/// Characters, of those that decoded with confidence, the sense is voted
/// over...
const VOTE_LEN: usize = 48;
/// ...at least this many before it can change...
const VOTE_MIN: usize = 16;
/// ...and by this much.
const VOTE_MARGIN: i32 = 20;

/// How much a code looks like the idle NUL or running text.
fn plausible(code: u8) -> i32 {
    match code {
        0 | b'\r' | b'\n' => 2,
        b' ' => 2,
        b'0'..=b'9' | b'A'..=b'Z' | b'a'..=b'z' => 1,
        b'.' | b',' | b'?' | b'/' | b'-' | b'=' | b':' | b'\'' => 0,
        1..=31 | 127 => -2,
        b'@' | b'`' => -1,
        _ => 0,
    }
}

/// One interleave's decoder, gate and output.
struct Lane {
    cfg: Mt63Config,
    decoder: Decoder,
    /// Sustained agreement so far, in symbols, while shut.
    run: u32,
    open: bool,
    /// Symbols under the hold threshold while open.
    low: u32,
    last_offset: i32,
    /// Symbols waiting for the gate.
    held: VecDeque<Decoded>,
    /// Characters of this burst, while too few to print.
    burst: Vec<char>,
    /// The burst has been confirmed.
    confirmed: bool,
    lines: Lines,
    escape: bool,
    /// The data's sense, as the characters show it ([`Lane::vote`]).
    inverted: bool,
    recent: VecDeque<u8>,
    /// Symbols clock at the last printed character.
    last_char: u64,
    now: u64,
    printed: bool,
    chars: u64,
    center: Option<f32>,
    snr: Option<f32>,
    snr_sum: f32,
    snr_n: u32,
    /// Per-symbol diagnostics for the tests.
    #[cfg(test)]
    trace: Vec<(Decoded, bool, f32, f32, f32)>,
}

impl Lane {
    fn new(cfg: Mt63Config) -> Self {
        Self {
            cfg,
            decoder: Decoder::new(cfg.long, INTEG),
            run: 0,
            open: false,
            low: 0,
            last_offset: i32::MIN,
            held: VecDeque::new(),
            burst: Vec::new(),
            confirmed: false,
            lines: Lines::default(),
            escape: false,
            inverted: false,
            recent: VecDeque::new(),
            last_char: 0,
            now: 0,
            printed: false,
            chars: 0,
            center: None,
            snr: None,
            snr_sum: 0.0,
            snr_n: 0,
            #[cfg(test)]
            trace: Vec::new(),
        }
    }

    fn mode(&self) -> String {
        self.cfg.label()
    }

    /// One symbol from the front end.
    fn symbol(&mut self, data: &[f32; DATA_SCAN], front: &Front, events: &mut Vec<Mt63Event>) {
        let d = self.decoder.process(data);
        self.now += 1;
        #[cfg(test)]
        self.trace
            .push((d, front.locked, front.conf, front.freq_ofs, front.freq_dev));
        self.vote(&d);
        let steady = d.offset == self.last_offset;
        self.last_offset = d.offset;
        let settled = front.locked && front.freq_dev < 0.05 && d.smooth >= S_OPEN;
        let center = self.cfg.center_hz
            + front.freq_ofs * front.bin_hz()
            + d.offset as f32 * front.carrier_hz();
        if settled && d.raw >= CHAR_MIN + 1.0 {
            self.center = Some(center);
            if let Some(snr) = front.snr_db(d.offset) {
                self.snr_sum += snr;
                self.snr_n += 1;
                // Over the last few symbols of the steady part: when the
                // transmission ends the integrators fall away first.
                if self.snr_n >= SNR_AVERAGE {
                    self.snr = Some(self.snr_sum / self.snr_n as f32);
                    self.snr_sum = 0.0;
                    self.snr_n = 0;
                }
            }
        }
        if self.open {
            if d.smooth < S_HOLD {
                self.low += 1;
                if self.low >= CLOSE_RUN {
                    self.close(events);
                    return;
                }
            } else {
                self.low = 0;
            }
            self.emit(d, events);
        } else {
            let good = front.locked && d.smooth >= S_OPEN && steady;
            self.run = if good { self.run + 1 } else { 0 };
            self.held.push_back(d);
            while self.held.len() > HELD {
                self.held.pop_front();
            }
            if self.run >= OPEN_RUN {
                self.open = true;
                self.low = 0;
                for d in std::mem::take(&mut self.held) {
                    self.emit(d, events);
                }
            }
        }
    }

    /// Which sense the data is in: every bit of a character is inverted
    /// when the synchronizer settles a half turn out of its frequency
    /// ambiguity (1.28 FFT bins, a differential phase of 180 degrees), and a
    /// signal read inverted has code 64 where it has NUL and so on. Nothing
    /// in the signal marks the sense; the characters show it: inverted
    /// text has controls for its capitals and a stream of `@` where the
    /// sender idles on NUL.
    fn vote(&mut self, d: &Decoded) {
        if d.raw < CHAR_MIN {
            return;
        }
        self.recent.push_back(d.code);
        while self.recent.len() > VOTE_LEN {
            self.recent.pop_front();
        }
        if self.recent.len() < VOTE_MIN {
            return;
        }
        let as_read: i32 = self.recent.iter().map(|&c| plausible(c)).sum();
        let flipped: i32 = self.recent.iter().map(|&c| plausible(c ^ 0x40)).sum();
        let want = if flipped > as_read + VOTE_MARGIN {
            true
        } else if as_read > flipped + VOTE_MARGIN {
            false
        } else {
            self.inverted
        };
        if want != self.inverted {
            self.inverted = want;
            if !self.confirmed {
                self.burst.clear();
            }
        }
    }

    fn close(&mut self, events: &mut Vec<Mt63Event>) {
        self.open = false;
        self.run = 0;
        self.held.clear();
        if self.confirmed {
            if let Some(line) = self.lines.take() {
                self.event(line, events);
            }
        }
        self.burst.clear();
        self.confirmed = false;
    }

    /// A symbol's character through the 8-bit escape and the burst gate.
    fn emit(&mut self, d: Decoded, events: &mut Vec<Mt63Event>) {
        if d.raw < CHAR_MIN {
            return;
        }
        let mut c = d.code as u32 ^ if self.inverted { 0x40 } else { 0 };
        if self.cfg.eight_bit {
            if c < 8 && !self.escape {
                return;
            }
            if c == 127 {
                self.escape = true;
                return;
            }
            if self.escape {
                c += 128;
                self.escape = false;
            }
        }
        let ch = match c {
            13 | 10 => '\n',
            9 => ' ',
            0x20..=0x7e => char::from(c as u8),
            0xa0..=0xff if self.cfg.eight_bit => char::from(c as u8),
            _ => return,
        };
        if !self.confirmed {
            self.burst.push(ch);
            let solid: Vec<char> = self
                .burst
                .iter()
                .copied()
                .filter(|c| !c.is_whitespace())
                .collect();
            let mut distinct = solid.clone();
            distinct.sort_unstable();
            distinct.dedup();
            if solid.len() >= MIN_BURST && distinct.len() >= 3 {
                self.confirmed = true;
                for ch in std::mem::take(&mut self.burst) {
                    self.print(ch, events);
                }
            } else if solid.len() >= 3 * MIN_BURST {
                // Many characters, too few different ones: not a text.
                self.burst.clear();
            }
        } else {
            self.print(ch, events);
        }
    }

    fn print(&mut self, ch: char, events: &mut Vec<Mt63Event>) {
        self.printed = true;
        self.last_char = self.now;
        if ch != '\n' {
            self.chars += 1;
        }
        if let Some(line) = self.lines.push(ch) {
            self.event(line, events);
        }
    }

    fn event(&mut self, text: String, events: &mut Vec<Mt63Event>) {
        events.push(Mt63Event::Text {
            text,
            mode: self.cfg.label(),
            center_hz: self.center.unwrap_or(self.cfg.center_hz),
            snr_db: self.snr.unwrap_or(f32::NEG_INFINITY),
        });
    }
}

/// One bandwidth's receiver with its interleaves.
struct Chain {
    front: Front,
    lanes: Vec<Lane>,
}

impl Chain {
    fn new(cfgs: &[Mt63Config]) -> Self {
        Self {
            front: Front::new(cfgs[0].bandwidth_hz, cfgs[0].center_hz, INTEG, DATA_DELAY),
            lanes: cfgs.iter().map(|c| Lane::new(*c)).collect(),
        }
    }

    fn push(&mut self, x: &[f32], events: &mut Vec<Mt63Event>) {
        let Self { front, lanes } = self;
        front.push(x, |data, front| {
            for l in lanes.iter_mut() {
                l.symbol(data, front, events);
            }
        });
    }

    fn band(&self) -> Option<(f32, f32)> {
        self.lanes.iter().find(|l| l.open).map(|l| {
            let bw = l.cfg.bandwidth_hz as f32;
            let c = l.center.unwrap_or(l.cfg.center_hz);
            (c - bw / 2.0, c + bw / 2.0)
        })
    }
}

/// MT63 receiver for one setting, or several side by side.
pub struct Mt63Decoder {
    resampler: Resampler,
    chains: Vec<Chain>,
    tmp: Vec<f32>,
    blanker: Blanker,
    blanked: Vec<f32>,
    events: Vec<Mt63Event>,
    samples: u64,
}

impl Mt63Decoder {
    /// One setting.
    pub fn new(fs: f32, cfg: Mt63Config) -> Self {
        Self::with_configs(fs, &[cfg])
    }

    /// 500, 1000 and 2000 Hz, long and short interleave, side by side:
    /// whichever the signal is, its receiver prints it.
    pub fn new_auto(fs: f32, center_hz: f32) -> Self {
        let mut c = Vec::new();
        for bw in [500, 1000, 2000] {
            for long in [true, false] {
                c.push(Mt63Config::new(bw, long, center_hz));
            }
        }
        Self::with_configs(fs, &c)
    }

    /// Several settings side by side. Settings of one bandwidth and center
    /// share the synchronizer and demodulator, which do not depend on the
    /// interleave.
    pub fn with_configs(fs: f32, cfgs: &[Mt63Config]) -> Self {
        let default = [Mt63Config::default()];
        let cfgs = if cfgs.is_empty() { &default[..] } else { cfgs };
        let mut chains: Vec<(u32, u32, Vec<Mt63Config>)> = Vec::new();
        for c in cfgs {
            let center = c.center_hz.to_bits();
            match chains
                .iter_mut()
                .find(|(b, cc, _)| *b == c.bandwidth_hz && *cc == center)
            {
                Some((_, _, v)) => v.push(*c),
                None => chains.push((c.bandwidth_hz, center, vec![*c])),
            }
        }
        Self {
            resampler: Resampler::new(fs, RATE, 3000.0, 5000.0),
            chains: chains.iter().map(|(_, _, v)| Chain::new(v)).collect(),
            tmp: Vec::with_capacity(4096),
            blanker: Blanker::new(RATE),
            blanked: Vec::with_capacity(4096),
            events: Vec::new(),
            samples: 0,
        }
    }

    pub fn push(&mut self, audio: &[f32]) {
        self.tmp.clear();
        self.resampler.process(audio, &mut self.tmp);
        self.blanked.clear();
        for &x in &self.tmp {
            if let Some((y, _)) = self.blanker.push(x) {
                self.blanked.push(y);
            }
        }
        self.samples += self.blanked.len() as u64;
        for c in self.chains.iter_mut() {
            c.push(&self.blanked, &mut self.events);
        }
        let band = self.chains.iter().find_map(|c| c.band());
        self.blanker.set_pair(band);
        let flush_symbols = FLUSH_S * 20.0;
        for chain in self.chains.iter_mut() {
            for l in chain.lanes.iter_mut() {
                if !l.lines.is_empty() && (l.now - l.last_char) as f32 > flush_symbols {
                    if let Some(line) = l.lines.take() {
                        l.event(line, &mut self.events);
                    }
                }
            }
        }
    }

    pub fn take(&mut self) -> Vec<Mt63Event> {
        std::mem::take(&mut self.events)
    }

    /// Print whatever text is pending.
    pub fn flush(&mut self) {
        for chain in self.chains.iter_mut() {
            for l in chain.lanes.iter_mut() {
                if l.confirmed {
                    if let Some(line) = l.lines.take() {
                        l.event(line, &mut self.events);
                    }
                }
            }
        }
    }

    pub fn status(&self) -> Mt63Status {
        let lanes = || self.chains.iter().flat_map(|c| c.lanes.iter());
        let lane = lanes()
            .filter(|l| l.printed)
            .max_by_key(|l| l.last_char)
            .or_else(|| lanes().next())
            .expect("at least one lane");
        Mt63Status {
            locked: lanes().any(|l| l.open && l.confirmed),
            center_hz: lane.center.unwrap_or(lane.cfg.center_hz),
            snr_db: lane.snr,
            mode: lane.mode(),
            chars: lanes().map(|l| l.chars).sum(),
        }
    }
}
