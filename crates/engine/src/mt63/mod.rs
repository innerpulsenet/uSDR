//! MT63 (Pawel Jalocha, SP9VRC), received the way his code as carried by
//! fldigi does it.
//!
//! An MT63 signal is 64 carriers of differential BPSK filling a bandwidth of
//! 500, 1000 or 2000 Hz, 5, 10 or 20 symbols a second. Even and odd carriers
//! are staggered by half a symbol. Each 7-bit character picks a row of a
//! 64-point Walsh matrix; the row's 64 bits go on the 64 carriers, each
//! carrier delayed by its own share of a 32 or 64 symbol interleaver.
//!
//! The synchronizer works from the signal alone. Four slices a symbol are
//! taken through the FFT; each bin's squared differential against the slice
//! one symbol back shows the BPSK carriers and their timing, and the fit
//! across the carrier pattern gives the symbol shift and the frequency
//! offset. The demodulator takes each carrier's differential phase. The
//! decoder deinterleaves and Walsh-transforms at every candidate carrier
//! offset and keeps the one that decodes best.
//!
//! fldigi prints whatever comes out. Interference can steer the Walsh peak,
//! so here nothing prints until the synchronizer has locked and the decoder
//! has held one carrier offset with a strong peak for [`OPEN_RUN`] symbols,
//! and a burst of less than [`MIN_BURST`] characters, or with fewer than
//! three different ones, is dropped.
//!
//! Measured on the tests' channel (30 Hz off, 60 ppm), the worst of three
//! runs: under 2% character errors down to -8 dB for MT63-500, -6 dB for
//! MT63-1000L, -4 dB for MT63-1000S and -2 dB for MT63-2000, as SNR in
//! 2500 Hz.
//!
//! Tables (the symbol shape and interleave patterns) are in `tables.rs`,
//! generated by `gen_tables.py` from fldigi's `symbol.dat` and
//! `mt63intl.dat`.

