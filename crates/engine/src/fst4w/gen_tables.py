#!/usr/bin/env python3
"""Generate crates/engine/src/fst4w/tables.rs from the WSJT-X Fortran. usage: gen.py LIBDIR OUT"""
import re, sys
lib, out = sys.argv[1], sys.argv[2]
g = open(f"{lib}/fst4/ldpc_240_74_generator.f90").read()
rows = re.findall(r'"([0-9a-fA-F]{19})"', g)
assert len(rows) == 166
gen = []
for r in rows:
    v = 0
    for j, c in enumerate(r):
        n = int(c, 16)
        ib = 2 if j == 18 else 4
        for jj in range(1, ib + 1):
            icol = j * 4 + jj
            if n >> (4 - jj) & 1:
                v |= 1 << (icol - 1)
    assert v >> 74 == 0
    gen.append(v)
p = open(f"{lib}/fst4/ldpc_240_74_parity.f90").read()
def data(name):
    m = re.search(r'data\s+%s\s*/(.*?)/' % name, p, re.S)
    return [int(x) for x in re.findall(r'\d+', m.group(1))]
mn, nm, nrw = data('Mn'), data('Nm'), data('nrw')
assert len(mn) == 3 * 240 and len(nm) == 5 * 166 and len(nrw) == 166
assert sum(nrw) == 720, sum(nrw)
s = []
s.append("""//! The (240, 74) LDPC code of FST4W: its generator and its sparse parity
//! checks, generated by a script from WSJT-X's
//! `lib/fst4/ldpc_240_74_generator.f90` and `ldpc_240_74_parity.f90` (GPL-3,
//! Joe Taylor K1JT and Steven Franke K9AN); not edited by hand. Parity
//! indices are one-based, zero meaning none, as in the Fortran.
""")
s.append("/// Row `i` selects the message bits whose sum is parity bit `i`; bit `j` of\n/// the value (from the least significant) is message bit `j`, 74 in all.\n")
s.append("pub const GENERATOR: [u128; 166] = [\n")
for v in gen: s.append("    0x%019x,\n" % v)
s.append("];\n\n/// The three parity checks each code bit belongs to, by bit.\n")
s.append("pub const MN: [[u8; 3]; 240] = [\n")
for i in range(240): s.append("    [%d, %d, %d],\n" % tuple(mn[3*i:3*i+3]))
s.append("];\n\n/// The code bits each parity check covers, by check; `NRW` says how many\n/// of the five are used.\n")
s.append("pub const NM: [[u8; 5]; 166] = [\n")
for i in range(166): s.append("    [%d, %d, %d, %d, %d],\n" % tuple(nm[5*i:5*i+5]))
s.append("];\n\npub const NRW: [u8; 166] = [\n")
for i in range(0,166,20): s.append("    " + ", ".join(map(str, nrw[i:i+20])) + ",\n")
s.append("];\n")
open(out, "w").write("".join(s))
