#!/usr/bin/env python3
"""Generate tables.rs from fldigi's sources (read as text, never built).

    python3 -I gen_tables.py /path/to/fldigi/src > tables.rs

DominoEX's nibble codes come from dominoex/dominovar.cxx, Thor's extended
codes from thor/thorvaricode.cxx. Thor's primary alphabet is MFSK varicode,
which this crate already has (mfsk::varicode); the script compares that
table with mfsk/mfskvaricode.cxx and stops if they differ, and it also checks
dominovar.cxx's decode table against the inverse of its encode table.
"""
import pathlib
import re
import sys

root = pathlib.Path(sys.argv[1])
here = pathlib.Path(__file__).resolve().parent


def fail(msg):
    sys.exit("gen_tables: " + msg)


def body(src, name):
    m = re.search(name + r"[^=]*=\s*\{(.*?)\n\};", src, re.S)
    if not m:
        fail("no table " + name)
    return re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)


dom = (root / "dominoex/dominovar.cxx").read_text()
triples = [
    tuple(int(x) for x in t)
    for t in re.findall(r"\{\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\}", body(dom, "varicode"))
]
if len(triples) != 512:
    fail("expected 512 DominoEX codes, got %d" % len(triples))

dec = [int(x) for x in re.findall(r"-?\d+", body(dom, "varidecode"))]
if len(dec) != 4096:
    fail("expected 4096 DominoEX decode entries, got %d" % len(dec))


def nib_value(t):
    v = t[0]
    for n in t[1:]:
        if n & 8:
            v = (v << 4) | n
        else:
            break
    return v


bad = []
for i, t in enumerate(triples):
    want = i if i < 256 else (i - 256) | 0x100
    if dec[nib_value(t)] != want:
        bad.append((i, t, dec[nib_value(t)]))
print("// decode-table mismatches against the encode table: %d" % len(bad), file=sys.stderr)
for b in bad:
    print("//   %r" % (b,), file=sys.stderr)

thor = (root / "thor/thorvaricode.cxx").read_text()
sec = [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{3})", body(thor, "thor_varidecode"))]
if len(sec) != 91:
    fail("expected 91 Thor extended codes, got %d" % len(sec))

mfsk = (root / "mfsk/mfskvaricode.cxx").read_text(encoding="latin-1")
c_codes = re.findall(r'"([01]+)"', body(mfsk, r"char \*varicode\[\]"))
ours = re.findall(r'"([01]+)"', (here.parent / "mfsk/varicode.rs").read_text())
if c_codes[:256] != ours[:256] or len(c_codes) != 256:
    fail("mfsk varicode differs from fldigi's (%d, %d codes)" % (len(c_codes), len(ours)))


def rows(items, per):
    return "\n".join(
        "    " + " ".join(items[i : i + per]) for i in range(0, len(items), per)
    )


out = """//! DominoEX and Thor code tables. GENERATED by gen_tables.py from fldigi's
//! dominoex/dominovar.cxx and thor/thorvaricode.cxx; do not edit by hand.
//! Thor's primary alphabet is the MFSK varicode in `crate::mfsk::varicode`,
//! which the same script checked against fldigi's table.

/// DominoEX codes: up to three nibbles per byte, primary then secondary.
/// A nibble with the top bit clear starts a code; a continuation has it set;
/// a zero after the first nibble means the code ended.
#[rustfmt::skip]
pub(super) const DOMINO_CODES: [[u8; 3]; 512] = [
%s
];

/// Thor's extended 12-bit codes (the secondary alphabet, recognized so it can
/// be left out of the text).
#[rustfmt::skip]
pub(super) const THOR_SECONDARY: [u16; 91] = [
%s
];
""" % (
    rows(["[%d, %d, %d]," % t for t in triples], 8),
    rows(["0x%03X," % v for v in sec], 12),
)
sys.stdout.write(out)
