#!/usr/bin/env python3
"""Write crates/desktop/src/stations_data.rs from crates/desktop/data/hf-directory.json.

The JSON is the sourced station research (every entry names the page it
came from and the date it was fetched; see hf-directory-notes.md beside it).
Run this after updating it:

    python3 tools/gen-stations.py
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
d = json.loads((ROOT / "crates/desktop/data/hf-directory.json").read_text())
out = []
w = out.append


def rs(s):
    return json.dumps(s or "", ensure_ascii=False)


def hm(t):
    t = t.strip()
    return int(t[:2]) * 60 + int(t[2:4])


DAYS = {"sun": 0, "mon": 1, "tue": 2, "wed": 3, "thu": 4, "fri": 5, "sat": 6}


def days_mask(s):
    s = (s or "daily").lower()
    if "daily" in s or "unconfirmed" in s or "occasion" in s:
        return 0x7F
    m = re.match(r"(\w{3})\w*\s*-\s*(\w{3})", s)
    if m:
        a, b = DAYS[m.group(1)], DAYS[m.group(2)]
        mask, i = 0, a
        while True:
            mask |= 1 << i
            if i == b:
                break
            i = (i + 1) % 7
        return mask
    mask = 0
    for k, v in DAYS.items():
        if k in s:
            mask |= 1 << v
    return mask or 0x7F


def windows(text):
    """'0230-1039' -> [(start, end)]; anything else (all times) -> []"""
    return [(hm(a), hm(b)) for a, b in re.findall(r"\b(\d{4})\s*-\s*(\d{4})\b", text or "")]


def slot(start, minutes, title, days=0x7F):
    return f"Slot {{ start_min: {start}, minutes: {minutes}, title: {rs(title)}, days: {days:#04x} }}"


def station(call, name, region, freqs, note="", sched=(), wins=()):
    f = ", ".join(f"{x:.1f}" for x in freqs)
    s = ", ".join(sched)
    ws = ", ".join(f"({k:.1f}, {a}, {b})" for k, a, b in wins)
    return f"    Station {{ call: {rs(call)}, name: {rs(name)}, region: Region::{region}, freqs_khz: &[{f}], note: {rs(note)}, schedule: &[{s}], windows: &[{ws}] }},"


w("//! Generated by tools/gen-stations.py from crates/desktop/data/hf-directory.json;")
w(f"//! the research fetched {d['fetched']}. Edit the JSON and run the script, not this file.")
w("")
w("use crate::directory::{Region, Slot, Station};")
w("")

# Radiofax.
region = {"NMF": "NorthAmerica", "NMG": "NorthAmerica", "NMC": "Pacific", "NOJ": "Pacific", "KVM70": "Pacific", "GYA": "Europe"}
w("pub const WEFAX: &[Station] = &[")
for e in d["wefax"]:
    call = "DDH/DDK" if e["call"].startswith("DDH") else e["call"].replace(" ", "")
    reg = region.get(e["call"], "Europe")
    sched = []
    for p in e.get("schedule", []):
        t = p["title"].strip()
        if p.get("valid_utc"):
            t += f" (valid {p['valid_utc']}Z)"
        sched.append(slot(hm(p["utc"]), p.get("minutes") or 0, t))
    wins = []
    for x in e.get("freq_windows_utc") or []:
        for a, b in windows(x.get("utc")):
            wins.append((x["khz"], a, b))
    dated = e.get("source_dated") or ""
    m = re.search(r"effective ([A-Za-z]+\.? \d+, \d{4})", dated) or re.search(r"\(([A-Za-z]+\.? \d{4})\)", dated) or re.search(r"DATED ([A-Za-z]+ \d+, \d{4})", dated)
    note = f"Schedule of {m.group(1)}" if m else ""
    if e["call"] == "GYA":
        note += " (partial; from the NWS worldwide list)"
    w(station(call, e["name"], reg, e["freqs_khz"], note, sched, wins))
# Halifax: on the old list, no current official source (see the notes).
w(station("CFH", "Halifax, Canadian Forces", "NorthAmerica", [4271.0, 6496.4, 10536.0, 13510.0], "No current official schedule found; may be off the air."))
w("];")
w("")

# NAVTEX: a ten-minute slot each, every four hours.
w("pub const NAVTEX: &[Station] = &[")
for e in sorted(d["navtex"], key=lambda e: (e["freq_khz"], e["name"])):
    sched = [slot(hm(t), 10, "Broadcast" + (" (Notices to Mariners)" if t in (e.get("nm_repeat_utc") or []) else "")) for t in e["times_utc"]]
    w(station(e["id"], e["name"], "NorthAmerica", [float(e["freq_khz"])], "", sched))
w("];")
w("")

# HFDL ground stations.
def hfdl_region(e):
    if any(k in e["name"] for k in ("Hawaii", "Guam", "Fiji", "New Zealand", "Australia")):
        return "Pacific"
    if any(k in e["name"] for k in ("Thailand", "Korea", "Russia", "Bahrain")):
        return "Asia"
    if "Canarias" in e["name"]:
        return "Atlantic"
    if -170 < e["lon"] < -50 and e["lat"] > 10:
        return "NorthAmerica"
    if -170 >= e["lon"] or e["lon"] > 100:
        return "Pacific"
    if -50 <= e["lon"] < 40 and e["lat"] > 30:
        return "Europe"
    return "Elsewhere"

w("pub const HFDL: &[Station] = &[")
for e in sorted(d["hfdl"], key=lambda e: ({"NorthAmerica": 0, "Atlantic": 1, "Europe": 2, "Pacific": 3, "Asia": 4}.get(hfdl_region(e), 5), e["gs_id"])):
    w(station(str(e["gs_id"]), e["name"], hfdl_region(e), e["freqs_khz"]))
w("];")
w("")
w(f"pub const HFDL_TABLE_VERSION: u32 = {d['hfdl_systable_version']};")
w("")

# DSC.
dsc = d["dsc"]
w("pub const DSC: &[Station] = &[")
w(station("DSC", "Distress and safety calling (MF and HF)", "Worldwide", dsc["distress_khz"], "Every ship and coast station keeps watch here; distress, urgency and safety calls and their acknowledgments."))
for c in dsc.get("coast_stations_nearby", []):
    w(station(c["mmsi"], c["name"], "NorthAmerica", c["freqs_khz"], ""))
w("];")
w("")

# The time stations.
w("pub const WWV: &[Station] = &[")
for e in d["wwv"]:
    w(station(e["call"], e["location"], "NorthAmerica" if e["call"] == "WWV" else "Pacific", [float(x) for x in e["freqs_khz"]], e.get("power_note", "")))
w("];")
w("")

# DRM: a row a broadcast, by the time it begins.
def drm_rows(entries, region):
    rows = []
    for e in entries:
        lang = e.get("language") or "language not given"
        who = e["station"].replace("Radio Romania International", "RRI").replace("TDF / Radio France Internationale", "TDF / RFI")
        title = f"{who} · {lang} to {e['target']}"
        bits = []
        if e.get("power_kw"):
            bits.append(f"{e['power_kw']:.0f} kW")
        if e["days"] and "daily" not in e["days"].lower():
            bits.append(e["days"])
        if e["drm_org_confidence"] != "confirmed":
            bits.append(e["drm_org_confidence"])
        for a, b in re.findall(r"(\d{4})-(\d{4})", e["utc"]):
            sa, sb = hm(a), hm(b)
            rows.append((sa, f"{a}–{b}", title, " · ".join(bits), e["freq_khz"], slot(sa, (sb - sa) % 1440, title, days_mask(e["days"]))))
    for sa, call, title, note, khz, sl in sorted(rows):
        w(station(call, title, region, [khz], note, [sl]))

w("pub const DRM: &[Station] = &[")
drm_rows(d["drm"], "Atlantic")
drm_rows(d["drm_other"], "Asia")
w("];")
w("")

# SITOR-B broadcasts, one station a transmitter.
w("pub const SITOR: &[Station] = &[")
by = {}
for e in d["sitor"]:
    by.setdefault(e["what"], []).append(e)
for what, es in by.items():
    call = what.split(" - ")[0].replace("USCG ", "").replace("CCG ", "").split()[0]
    name = what.split(" - ")[0]
    freqs = sorted({e["freq_khz"] for e in es})
    times = sorted({t for e in es for t in e["times_utc"]})
    sched = [slot(hm(t), 0, what.split(" - ", 1)[-1]) for t in times]
    reg = "Pacific" if any(k in what for k in ("NMC", "NMO", "NRV")) else "NorthAmerica"
    note = "Not every frequency at every time: " + "; ".join(f"{e['freq_khz']:.1f} at {', '.join(e['times_utc'])}" for e in es) if len(es) > 1 else ""
    w(station(call, name, reg, freqs, note, sched))
w("];")

(ROOT / "crates/desktop/src/stations_data.rs").write_text("\n".join(out) + "\n")
print("wrote stations_data.rs")
