#!/usr/bin/env python3
"""Write crates/desktop/src/lookups_data.rs from crates/desktop/data/lookups.json:
the published tables the decodes' identifiers are translated with (ITU
MIDs and coast stations, ICAO address blocks and nationality marks, the
FAA's list of ICAO airline designators, ACARS labels, ISO 3166 and 639-2).
Each table's source and fetch date are in the JSON and lookups-notes.md.

    python3 tools/gen-lookups.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
d = json.loads((ROOT / "crates/desktop/data/lookups.json").read_text())
out = []
w = out.append


def rs(s):
    return json.dumps(s or "", ensure_ascii=False)


w("//! Generated by tools/gen-lookups.py from crates/desktop/data/lookups.json;")
w("//! edit the JSON and run the script, not this file.")
w("")
w("#![allow(dead_code)]")
w("")
w("pub const MID: &[(u16, &str)] = &[")
seen = set()
for e in d["mid"]["table"]:
    if e["mid"] in seen:
        continue
    seen.add(e["mid"])
    w(f"    ({e['mid']}, {rs(e['allocated_to'])}),")
w("];")
w("pub const COAST: &[(&str, &str)] = &[")
seen = set()
for e in d["coast_stations"]["table"]:
    if e["mmsi"] in seen:
        continue
    seen.add(e["mmsi"])
    w(f"    ({rs(e['mmsi'])}, {rs(e['name'].title())}),")
w("];")
w("pub const ICAO24: &[(u32, u32, &str)] = &[")
for e in d["icao24"]["table"]:
    w(f"    (0x{e['start_hex']}, 0x{e['end_hex']}, {rs(e['state'])}),")
w("];")
w("pub const REG_PREFIX: &[(&str, &str)] = &[")
for e in d["registration_prefixes"]["table"]:
    w(f"    ({rs(e['prefix'])}, {rs(e['state'])}),")
w("];")
w("pub const AIRLINES: &[(&str, &str, &str)] = &[")
for e in d["airlines"]["table"]:
    w(f"    ({rs(e['icao'])}, {rs(e['name'])}, {rs(e.get('country') or '')}),")
w("];")
w("pub const ACARS_LABELS: &[(&str, &str)] = &[")
for e in d["acars_labels"]["table"]:
    w(f"    ({rs(e['label'])}, {rs(e['meaning'])}),")
w("];")
w("pub const ISO3166: &[(&str, &str)] = &[")
for e in d["iso3166"]["table"]:
    for code in (e.get("alpha2"), e.get("alpha3")):
        if code:
            w(f"    ({rs(code)}, {rs(e['name'])}),")
w("];")
w("pub const ISO639: &[(&str, &str)] = &[")
for e in d["iso639_2"]["table"]:
    for code in (e.get("code"), e.get("terminologic"), e.get("alpha2")):
        if code:
            w(f"    ({rs(code)}, {rs(e['name'])}),")
w("];")
ship = next((x for x in d["lookups_online"] if x["what"].startswith("ship")), {})
air = next((x for x in d["lookups_online"] if "{hex" in (x.get("url_pattern") or "")), {})
w("/// ITU MARS's ship station search: no link goes straight to a ship, so")
w("/// the page is opened for the MMSI to be searched there.")
w(f"pub const MARS_SEARCH: &str = {rs(ship.get('search_page'))};")
w("/// An aircraft by its ICAO address, `{hex}` replaced.")
w(f"pub const AIRCRAFT_URL: &str = {rs((air.get('url_pattern') or '').replace('{hex_lowercase}', '{hex}'))};")
(ROOT / "crates/desktop/src/lookups_data.rs").write_text("\n".join(out) + "\n")
print("wrote lookups_data.rs", len(out), "lines")
